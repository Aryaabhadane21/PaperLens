/**
 * Generates an academic Markdown report of the paper analysis.
 */
export function generateMarkdown(result: PaperAnalysisResult): string {
  const { metadata, analysis, verification } = result;

  const lines: string[] = [];
  lines.push(`# ${analysis.title}`);
  lines.push('');
  lines.push(`> **Analysis Generated by PaperLens** | Date: ${new Date(result.createdAt).toLocaleDateString()} | Source: ${metadata.sourceType.toUpperCase()} | Word Count: ${metadata.wordCount.toLocaleString()}`);
  lines.push(`> **Verification Grounding Score**: ${verification.overallConfidenceScore}% (${verification.verifiedCount}/${verification.totalClaimsChecked} Claims Verified)`);
  lines.push('');
  lines.push('---');
  lines.push('');
  lines.push('## Executive Summary');
  lines.push('');
  lines.push(analysis.executiveSummary);
  lines.push('');

  lines.push('## 1. Problem Statement');
  lines.push('');
  lines.push(`**Core Challenge:** ${analysis.problem.statement}`);
  lines.push('');
  if (analysis.problem.contextAndSignificance) {
    lines.push(`**Context & Significance:** ${analysis.problem.contextAndSignificance}`);
    lines.push('');
  }
  if (analysis.problem.literatureGap) {
    lines.push(`**Literature Gap:** ${analysis.problem.literatureGap}`);
    lines.push('');
  }
  if (analysis.problem.keyChallenges?.length) {
    lines.push('**Key Technical Challenges:**');
    analysis.problem.keyChallenges.forEach((c) => lines.push(`- ${c}`));
    lines.push('');
  }

  lines.push('## 2. Objectives & Hypotheses');
  lines.push('');
  lines.push(`**Primary Objective:** ${analysis.objectives.primaryObjective}`);
  lines.push('');
  if (analysis.objectives.secondaryObjectives?.length) {
    lines.push('**Secondary Objectives:**');
    analysis.objectives.secondaryObjectives.forEach((o) => lines.push(`- ${o}`));
    lines.push('');
  }
  if (analysis.objectives.hypotheses?.length) {
    lines.push('**Hypotheses Tested:**');
    analysis.objectives.hypotheses.forEach((h) => lines.push(`- ${h}`));
    lines.push('');
  }

  lines.push('## 3. Methodology');
  lines.push('');
  lines.push(`**Research Design:** ${analysis.methodology.researchDesign}`);
  lines.push('');
  if (analysis.methodology.datasetOrParticipants) {
    lines.push(`**Dataset & Sample:** ${analysis.methodology.datasetOrParticipants}`);
    lines.push('');
  }
  if (analysis.methodology.toolsAndFrameworks?.length) {
    lines.push(`**Tools & Frameworks:** ${analysis.methodology.toolsAndFrameworks.join(', ')}`);
    lines.push('');
  }
  if (analysis.methodology.experimentalProcedure) {
    lines.push(`**Experimental Procedure:** ${analysis.methodology.experimentalProcedure}`);
    lines.push('');
  }
  if (analysis.methodology.evaluationMetrics?.length) {
    lines.push(`**Evaluation Metrics:** ${analysis.methodology.evaluationMetrics.join(', ')}`);
    lines.push('');
  }

  lines.push('## 4. Key Findings & Empirical Results');
  lines.push('');
  if (analysis.findings.keyResults?.length) {
    lines.push('**Primary Findings:**');
    analysis.findings.keyResults.forEach((r) => lines.push(`- ${r}`));
    lines.push('');
  }
  if (analysis.findings.quantitativeMetrics?.length) {
    lines.push('### Quantitative Metrics Table');
    lines.push('| Metric | Value | Baseline / Comparison |');
    lines.push('| :--- | :--- | :--- |');
    analysis.findings.quantitativeMetrics.forEach((m) => {
      lines.push(`| ${m.metricName} | **${m.value}** | ${m.baselineOrComparison || 'N/A'} |`);
    });
    lines.push('');
  }
  if (analysis.findings.mainTakeaways?.length) {
    lines.push('**Main Takeaways:**');
    analysis.findings.mainTakeaways.forEach((t) => lines.push(`- ${t}`));
    lines.push('');
  }

  lines.push('## 5. Limitations & Future Directions');
  lines.push('');
  if (analysis.limitations.methodologicalLimitations?.length) {
    lines.push('**Methodological Limitations:**');
    analysis.limitations.methodologicalLimitations.forEach((l) => lines.push(`- ${l}`));
    lines.push('');
  }
  if (analysis.limitations.threatsToValidity?.length) {
    lines.push('**Threats to Validity:**');
    analysis.limitations.threatsToValidity.forEach((t) => lines.push(`- ${t}`));
    lines.push('');
  }
  if (analysis.limitations.futureResearchDirections?.length) {
    lines.push('**Future Research Directions:**');
    analysis.limitations.futureResearchDirections.forEach((f) => lines.push(`- ${f}`));
    lines.push('');
  }

  lines.push('## 6. Factual Verification & Source Grounding');
  lines.push('');
  lines.push(verification.verificationNotes);
  lines.push('');
  verification.claims.forEach((c, idx) => {
    const statusIcon = c.status === 'verified' ? '✅ [VERIFIED]' : c.status === 'partially_verified' ? '⚠️ [PARTIAL]' : '❌ [UNVERIFIED]';
    lines.push(`### Claim ${idx + 1} (${c.section.toUpperCase()}): ${statusIcon} - ${c.confidenceScore}% Confidence`);
    lines.push(`> "${c.claim}"`);
    if (c.sourceQuote) {
      lines.push(`- **Evidence:** *"${c.sourceQuote}"*`);
    }
    lines.push(`- **Audit Note:** ${c.explanation}`);
    lines.push('');
  });

  return lines.join('\n');
}

/**
 * Generates a formatted Word Document (.docx) buffer.
 */
export async function generateWordBuffer(result: PaperAnalysisResult): Promise<Buffer> {
  const { analysis, verification, metadata } = result;

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            text: analysis.title,
            heading: HeadingLevel.TITLE,
          }),
          new Paragraph({
            children: [
              new TextRun({
                text: `PaperLens Analysis Report | Source: ${metadata.sourceType.toUpperCase()} | Grounding Confidence: ${verification.overallConfidenceScore}%`,
                italics: true,
                color: '64748B',
              }),
            ],
            spacing: { after: 300 },
          }),
          new Paragraph({
            text: 'Executive Summary',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          new Paragraph({
            text: analysis.executiveSummary,
            spacing: { after: 200 },
          }),

          // Problem
          new Paragraph({
            text: '1. Problem Statement',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          new Paragraph({
            children: [
              new TextRun({ text: 'Core Problem: ', bold: true }),
              new TextRun(analysis.problem.statement),
            ],
            spacing: { after: 100 },
          }),
          ...(analysis.problem.literatureGap
            ? [
                new Paragraph({
                  children: [
                    new TextRun({ text: 'Literature Gap: ', bold: true }),
                    new TextRun(analysis.problem.literatureGap),
                  ],
                  spacing: { after: 100 },
                }),
              ]
            : []),

          // Objectives
          new Paragraph({
            text: '2. Objectives & Hypotheses',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          new Paragraph({
            children: [
              new TextRun({ text: 'Primary Objective: ', bold: true }),
              new TextRun(analysis.objectives.primaryObjective),
            ],
            spacing: { after: 100 },
          }),
          ...analysis.objectives.secondaryObjectives.map(
            (o) => new Paragraph({ text: `• ${o}`, spacing: { after: 60 } })
          ),

          // Methodology
          new Paragraph({
            text: '3. Methodology',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          new Paragraph({
            children: [
              new TextRun({ text: 'Research Design: ', bold: true }),
              new TextRun(analysis.methodology.researchDesign),
            ],
            spacing: { after: 100 },
          }),
          ...(analysis.methodology.datasetOrParticipants
            ? [
                new Paragraph({
                  children: [
                    new TextRun({ text: 'Dataset / Sample: ', bold: true }),
                    new TextRun(analysis.methodology.datasetOrParticipants),
                  ],
                  spacing: { after: 100 },
                }),
              ]
            : []),

          // Findings
          new Paragraph({
            text: '4. Findings & Results',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          ...analysis.findings.keyResults.map(
            (r) => new Paragraph({ text: `• ${r}`, spacing: { after: 80 } })
          ),

          // Limitations
          new Paragraph({
            text: '5. Limitations & Future Directions',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          ...analysis.limitations.methodologicalLimitations.map(
            (l) => new Paragraph({ text: `• ${l}`, spacing: { after: 80 } })
          ),

          // Verification
          new Paragraph({
            text: '6. Factual Grounding & Claim Audit',
            heading: HeadingLevel.HEADING_1,
            spacing: { before: 200, after: 100 },
          }),
          new Paragraph({
            text: verification.verificationNotes,
            spacing: { after: 150 },
          }),
          ...verification.claims.map(
            (c) =>
              new Paragraph({
                children: [
                  new TextRun({ text: `[${c.status.toUpperCase()} - ${c.confidenceScore}%] `, bold: true, color: c.status === 'verified' ? '15803D' : 'B45309' }),
                  new TextRun({ text: c.claim, italics: true }),
                  new TextRun({ text: ` — Quote: "${c.sourceQuote || 'N/A'}"` }),
                ],
                spacing: { after: 100 },
              })
          ),
        ],
      },
    ],
  });

  return await Packer.toBuffer(doc);
}

/**
 * Generates a clean PDF document buffer using PDFKit.
 */
export function generatePdfBuffer(result: PaperAnalysisResult): Promise<Buffer> {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: 'A4' });
    const chunks: Buffer[] = [];

    doc.on('data', (chunk) => chunks.push(chunk));
    doc.on('end', () => resolve(Buffer.concat(chunks)));
    doc.on('error', (err) => reject(err));

    const navy = '#0a192f';
    const gold = '#b45309';
    const gray = '#475569';
    const dark = '#1e293b';

    // Header banner
    doc.rect(0, 0, doc.page.width, 100).fill(navy);
    doc.fillColor('#ffffff').fontSize(18).font('Helvetica-Bold').text('PaperLens Academic Synthesis', 50, 30);
    doc.fontSize(10).font('Helvetica').fillColor('#94a3b8').text(`Grounding Confidence: ${result.verification.overallConfidenceScore}% | Date: ${new Date().toLocaleDateString()}`, 50, 55);

    doc.y = 120;
    doc.fillColor(navy).fontSize(16).font('Helvetica-Bold').text(result.analysis.title, 50, doc.y);
    doc.moveDown(0.5);

    // Executive Summary
    doc.fillColor(gold).fontSize(12).font('Helvetica-Bold').text('Executive Summary');
    doc.moveDown(0.2);
    doc.fillColor(dark).fontSize(10).font('Helvetica').text(result.analysis.executiveSummary, { lineGap: 3 });
    doc.moveDown(0.8);

    // Section 1: Problem
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('1. Problem Statement');
    doc.moveDown(0.2);
    doc.fillColor(dark).fontSize(10).font('Helvetica').text(`Statement: ${result.analysis.problem.statement}`, { lineGap: 2 });
    if (result.analysis.problem.literatureGap) {
      doc.moveDown(0.2);
      doc.text(`Literature Gap: ${result.analysis.problem.literatureGap}`, { lineGap: 2 });
    }
    doc.moveDown(0.8);

    // Section 2: Objectives
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('2. Objectives & Hypotheses');
    doc.moveDown(0.2);
    doc.fillColor(dark).fontSize(10).font('Helvetica').text(`Primary Objective: ${result.analysis.objectives.primaryObjective}`, { lineGap: 2 });
    for (const obj of result.analysis.objectives.secondaryObjectives || []) {
      doc.text(`• ${obj}`, { lineGap: 2, indent: 10 });
    }
    doc.moveDown(0.8);

    // Section 3: Methodology
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('3. Methodology');
    doc.moveDown(0.2);
    doc.fillColor(dark).fontSize(10).font('Helvetica').text(`Design: ${result.analysis.methodology.researchDesign}`, { lineGap: 2 });
    if (result.analysis.methodology.datasetOrParticipants) {
      doc.text(`Dataset: ${result.analysis.methodology.datasetOrParticipants}`, { lineGap: 2 });
    }
    doc.moveDown(0.8);

    // Section 4: Key Findings
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('4. Key Findings');
    doc.moveDown(0.2);
    for (const finding of result.analysis.findings.keyResults || []) {
      doc.fillColor(dark).fontSize(10).font('Helvetica').text(`• ${finding}`, { lineGap: 2, indent: 10 });
    }
    for (const metric of result.analysis.findings.quantitativeMetrics || []) {
      doc.text(`  - ${metric.metricName}: ${metric.value} (${metric.baselineOrComparison || 'vs baseline'})`, { indent: 15 });
    }
    doc.moveDown(0.8);

    // Section 5: Limitations
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('5. Limitations & Future Work');
    doc.moveDown(0.2);
    for (const lim of result.analysis.limitations.methodologicalLimitations || []) {
      doc.fillColor(dark).fontSize(10).font('Helvetica').text(`• ${lim}`, { lineGap: 2, indent: 10 });
    }
    doc.moveDown(0.8);

    // Section 6: Verification
    doc.fillColor(navy).fontSize(12).font('Helvetica-Bold').text('6. Factual Verification & Citations');
    doc.moveDown(0.2);
    doc.fillColor(gray).fontSize(9).font('Helvetica-Oblique').text(result.verification.verificationNotes);
    doc.moveDown(0.4);
    for (const c of (result.verification.claims || []).slice(0, 5)) {
      const tag = c.status === 'verified' ? '[VERIFIED]' : '[PARTIAL]';
      doc.fillColor(c.status === 'verified' ? '#15803d' : '#b45309').fontSize(9).font('Helvetica-Bold').text(`${tag} (${c.confidenceScore}%) - ${c.section.toUpperCase()}`);
      doc.fillColor(dark).fontSize(9).font('Helvetica').text(`Claim: ${c.claim}`, { indent: 10 });
      if (c.sourceQuote) {
        doc.fillColor(gray).fontSize(8).font('Helvetica-Oblique').text(`Quote: "${c.sourceQuote}"`, { indent: 15 });
      }
      doc.moveDown(0.3);
    }

    doc.end();
  });
}
